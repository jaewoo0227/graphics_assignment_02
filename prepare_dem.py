"""Regenerate the offline WebGL grid from the included GMT NetCDF file."""
from base64 import b64encode
from hashlib import sha256
from pathlib import Path

import numpy as np
from osgeo import gdal

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "earth_relief_10m_g.grd"
EXPECTED = "4b64b4dd46d26d07c8542a46edec205c08a7b248ac8ab53610407ae4ebf2af57"


def main():
    if sha256(SOURCE.read_bytes()).hexdigest() != EXPECTED:
        raise ValueError("Unexpected source grid checksum")
    gdal.UseExceptions()
    grid = gdal.Open(str(SOURCE))
    band = grid.GetRasterBand(1)
    raw = band.ReadAsArray()
    if raw.shape != (1081, 2161) or np.any(raw == band.GetNoDataValue()):
        raise ValueError("Unexpected grid dimensions or missing elevations")
    # GDAL returns northern rows first. Preserve half-metres and omit +180°,
    # whose data duplicate the -180° meridian.
    assert band.GetScale() == 0.5 and band.GetOffset() in (None, 0)
    assert np.array_equal(raw[:, 0], raw[:, -1])
    sampled = raw[::3, :-1:3].astype("<i2")
    encoded = b64encode(sampled.tobytes()).decode("ascii")
    js = (f'// Generated by tools/prepare_dem.py; north to south, west to east.\n'
          f'const DEM = Object.freeze({{rows: 361, cols: 720, step: 0.5, '
          f'metresPerUnit: 0.5, packed: "{encoded}"}});\n')
    (ROOT / "dem.js").write_text(js, encoding="utf-8")
    print(f"{sampled.shape}, {sampled.min()/2:g} to {sampled.max()/2:g} m")


if __name__ == "__main__":
    main()
